using JasperFx.Descriptors;

namespace JasperFx.Events.EventModeling;

/// <summary>
/// How many values a field holds (jasperfx#1299).
/// </summary>
/// <remarks>
/// Goes over the wire as an integer under the STJ defaults, so append new members; never renumber.
/// </remarks>
public enum FieldCardinality
{
    /// <summary>One value.</summary>
    One = 0,

    /// <summary>A collection of values of <see cref="FieldDescriptor.Type"/>.</summary>
    Many = 1,
}

/// <summary>
/// Where a declared field's value comes from: a field of another modelled type (jasperfx#1299). The
/// board's <c>mapping</c>, and what the information-completeness check follows when names differ.
/// </summary>
/// <param name="Source">The type the value is read from — a consumed event, the command, the aggregate.</param>
/// <param name="Field">The name of the field on <paramref name="Source"/>.</param>
public sealed record FieldMappingDescriptor(TypeDescriptor Source, string Field);

/// <summary>
/// One field of a modelled type (jasperfx#1299): a flat field, or one level of nesting by reference — a
/// field whose <see cref="Type"/> is itself a modelled type is a reference to that element, which is what
/// reflection sees. No schema language.
/// </summary>
/// <remarks>
/// <para>
/// Derived from the record types by the source generator (into the event-model manifest, AOT-clean) or by
/// reflection at describe time; declared with <c>EventModelBuilder.Shape&lt;T&gt;().Field("Total")…</c> for
/// stub-first work. Example values stay on the scenario, never on the field.
/// </para>
/// <para>
/// The flags reflection cannot see come from attributes: <c>[Generated]</c> and <c>[Pii]</c> in JasperFx,
/// <c>[Identity]</c> or <c>[Key]</c> for <see cref="Identity"/>, and <c>[Required]</c> to override
/// <see cref="Optional"/>. Tags come from the registry.
/// </para>
/// </remarks>
/// <param name="Name">The field's name.</param>
/// <param name="Type">The field's type — the element type when <see cref="Cardinality"/> is <see cref="FieldCardinality.Many"/>.</param>
public sealed record FieldDescriptor(string Name, TypeDescriptor Type)
{
    /// <summary>One value or many.</summary>
    public FieldCardinality Cardinality { get; init; } = FieldCardinality.One;

    /// <summary>The field may be absent or null.</summary>
    public bool Optional { get; init; }

    /// <summary>The field identifies the thing: a stream id, a strong-typed id, <c>[Identity]</c>, <c>[Key]</c>.</summary>
    public bool Identity { get; init; }

    /// <summary>The consistency tag this field's value is, as the model's tag catalogue names it (jasperfx#1297). Null when none.</summary>
    public string? Tag { get; init; }

    /// <summary>
    /// The value is generated by the system — an id minted on the way in, a timestamp — so no command or
    /// event has to supply it. <c>[Generated]</c>. The information-completeness check exempts it.
    /// </summary>
    public bool Generated { get; init; }

    /// <summary>The value is personally identifiable information. <c>[Pii]</c>.</summary>
    public bool Pii { get; init; }

    /// <summary>Where the value comes from, when a declaration said and the names differ. Null otherwise.</summary>
    public FieldMappingDescriptor? Mapping { get; init; }

    /// <summary>Plain text or markdown describing the field (jasperfx#1298). Null when none.</summary>
    public string? Description { get; init; }

    /// <summary>Display form: <c>Total: Decimal</c>, with <c>[]</c> for many and <c>?</c> for optional.</summary>
    public override string ToString()
        => $"{Name}: {Type.Name}{(Cardinality == FieldCardinality.Many ? "[]" : "")}{(Optional ? "?" : "")}";
}
